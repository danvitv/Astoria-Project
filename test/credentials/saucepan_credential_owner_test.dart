final class _Backing extends SharedPreferencesStorePlatform {
  _Backing(Map<String, Object> initial)
    : values = {for (final e in initial.entries) 'flutter.${e.key}': e.value};
  final Map<String, Object> values;
  final writes = <String>[];
  bool rejectWrites = false;
  Future<void> Function()? beforeMetadata;
  @override
  Future<Map<String, Object>> getAll() async => Map.of(values);
  @override
  Future<bool> setValue(String type, String key, Object value) async {
    writes.add(key);
    if (key == 'flutter.gz_saucepan_handle') await beforeMetadata?.call();
    if (rejectWrites) return false;
    values[key] = value;
    return true;
  }

  @override
  Future<bool> remove(String key) async {
    writes.add(key);
    if (key == 'flutter.gz_saucepan_handle') await beforeMetadata?.call();
    if (rejectWrites) return false;
    values.remove(key);
    return true;
  }

  @override
  Future<bool> clear() async {
    writes.add('*');
    values.clear();
    return true;
  }
}

Future<void> _backed(
  Future<void> Function(TrackedSharedPreferences prefs, _Backing backing)
  body, {
  Map<String, Object> initial = const {
    _key: _legacy,
    'gz_saucepan_handle': 'OLD_HANDLE',
  },
}) async {
  SharedPreferences.setMockInitialValues(initial);
  final previous = SharedPreferencesStorePlatform.instance;
  final backing = _Backing(initial);
  SharedPreferencesStorePlatform.instance = backing;
  try {
    final prefs = await TrackedSharedPreferences.getInstance();
    await body(prefs as TrackedSharedPreferences, backing);
  } finally {
    SharedPreferencesStorePlatform.instance = previous;
  }
}

final class _Adapter implements HttpClientAdapter {
  _Adapter(this.reply);
  final FutureOr<({int status, String body})> Function(RequestOptions) reply;
  final requests = <RequestOptions>[];
  @override
  Future<ResponseBody> fetch(
    RequestOptions options,
    Stream<Uint8List>? requestStream,
    Future<void>? cancelFuture,
  ) async {
    requests.add(options);
    final response = await reply(options);
    return ResponseBody.fromString(
      response.body,
      response.status,
      headers: {
        Headers.contentTypeHeader: ['application/json'],
      },
    );
  }

  @override
  void close({bool force = false}) {}
}

