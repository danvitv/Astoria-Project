bool isDiagnosticPath(String path) {
  if (path == r'$') return true;
  final base = path.endsWith('.*') ? path.substring(0, path.length - 2) : path;
  for (final schema in diagnosticSchemas.entries) {
    if (schema.value.contains(base)) return true;
    if (schema.key.endsWith('[]') || schema.key == 'baseline') {
      if (base == schema.key) return true;
      if (schema.value.any((field) => base == '${schema.key}.$field')) {
        return true;
      }
    }
  }
  return false;
}
